def _print_qr(url: str) -> None:
    """Show a scannable code so a phone can open the app without typing."""
    try:
        import qrcode

        q = qrcode.QRCode(border=1)
        q.add_data(url)
        q.make(fit=True)
        m = q.get_matrix()
        print()
        # two rows per line of text, using half-block characters
        for y in range(0, len(m), 2):
            line = ""
            for x in range(len(m[0])):
                top = m[y][x]
                bottom = m[y + 1][x] if y + 1 < len(m) else False
                line += "█" if top and bottom else "▀" if top else "▄" if bottom else " "
            print("  " + line)
        print(f"\n  scan to open {url}")
    except Exception:
        pass


def _lan_addresses() -> list[str]:
    import socket
    import subprocess

    out = subprocess.run(["ip", "-4", "-o", "addr", "show", "scope", "global"],
                         capture_output=True, text=True).stdout
    ips = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) > 3 and not parts[1].startswith(("docker", "br-", "veth")):
            ips.append(parts[3].split("/")[0])
    return ips or [socket.gethostbyname(socket.gethostname())]


