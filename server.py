"""VAD conversation server: static front-end + Bengali ASR + local text generation.

Pipeline per turn:
  browser VAD cuts a speech segment  ->  POST /api/sessions/{id}/turns
  -> WAV saved under conversations/<session>/
  -> transcribed with ehzawad/stt_bn_fastconformer_ctc  (asr.py)
  -> optional reply generated by a local Ollama model   (llm.py)

Run with the project venv so NeMo is importable:
    .venv/bin/python server.py
"""
from __future__ import annotations

import asyncio
import json
import logging
import os
import re
import time
import uuid
from contextlib import asynccontextmanager
from collections import deque
from pathlib import Path

from fastapi import FastAPI, File, Form, HTTPException, UploadFile, Request
from fastapi.responses import FileResponse, JSONResponse, Response
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field
from starlette.concurrency import run_in_threadpool

import asr
import llm
import tts
from streaming import router as streaming_router

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
log = logging.getLogger("server")

ROOT = Path(__file__).resolve().parent
STATIC = ROOT / "static"
CONVS = ROOT / "conversations"
CONVS.mkdir(exist_ok=True)

SAFE_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
WAV_NAME = re.compile(r"^turn-\d{4}-(file|mic)\.wav$")

# One writer at a time per session: mic turns, file turns and replies can all
# land concurrently, and each one appends to the same turns.json.
_locks: dict[str, asyncio.Lock] = {}
_replies: dict[tuple[str, str], asyncio.Task] = {}
_interrupted: dict[str, deque] = {}


def _lock(session_id: str) -> asyncio.Lock:
    return _locks.setdefault(session_id, asyncio.Lock())


@asynccontextmanager
async def lifespan(app: FastAPI):
    asr.start_loading()          # background; server answers immediately
    yield


app = FastAPI(title="Bengali Voice Bot", lifespan=lifespan)
app.include_router(streaming_router)


# ---------------------------------------------------------------- storage --
def _session_dir(session_id: str, create: bool = False) -> Path:
    if not SAFE_ID.match(session_id):
        raise HTTPException(400, "bad session id")
    d = CONVS / session_id
    if create:
        d.mkdir(parents=True, exist_ok=True)
    elif not d.is_dir():
        raise HTTPException(404, "unknown session")
    return d


def _load(d: Path) -> list[dict]:
    p = d / "turns.json"
    return json.loads(p.read_text()) if p.exists() else []


def _save(d: Path, turns: list[dict]) -> None:
    tmp = d / "turns.json.tmp"
    tmp.write_text(json.dumps(turns, ensure_ascii=False, indent=2))
    os.replace(tmp, d / "turns.json")


